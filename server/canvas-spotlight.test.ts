import { afterEach, describe, expect, it, vi } from 'vitest'
import { CanvasSpotlightStore } from './canvas-spotlight.js'
afterEach(() => vi.useRealTimers())
describe('CanvasSpotlightStore', () => {
  it('has one pending request, supersedes and settles once', async () => {
    const store = new CanvasSpotlightStore(() => 123)
    const first = store.requestSpotlight('w-one', { label: 'Row', frame: 'settings' }, 'claude')
    const waiting = store.wait(first.id, 60000)
    expect(store.pending()['w-one']).toEqual({ ...first, requestedAt: 123, requestedBy: 'claude' })
    const second = store.requestSpotlight('w-one', { labelId: 'row' })
    expect(await waiting).toBe('superseded')
    expect(store.lookup(first.id)?.decision).toBe('superseded')
    expect(store.settle(first.id, 'accepted')).toBe(false)
    const accepted = store.wait(second.id, 60000)
    expect(store.settle(second.id, 'accepted')).toBe(true)
    expect(await accepted).toBe('accepted')
    expect(store.pending()).toEqual({})
  })
  it('dismisses, closes missing tabs, preserves outcomes and bounds settled history', async () => {
    const store = new CanvasSpotlightStore()
    const first = store.requestSpotlight('w-one', { frame: 'settings' })
    store.settle(first.id, 'dismissed')
    expect(await store.wait(first.id, 60000)).toBe('dismissed')
    const closed = store.requestSpotlight('w-two', { frame: 'accounts' })
    const waiting = store.wait(closed.id, 60000)
    store.retain(new Set(['w-one']))
    expect(await waiting).toBe('closed')
    expect(store.lookup(closed.id)?.decision).toBe('closed')
    expect(await store.wait('unknown', 60000)).toBe('closed')
    for (let i = 0; i < 300; i++) store.settle(store.requestSpotlight('w-one', { label: 'Row' }).id, 'accepted')
    expect(store.lookup(first.id)).toBeUndefined()
  })
  it('returns pending on timeout/abort, then allows later decisions', async () => {
    vi.useFakeTimers()
    const store = new CanvasSpotlightStore(), request = store.requestSpotlight('w-one', { label: 'Row' })
    const waiting = store.wait(request.id, 60000)
    await vi.advanceTimersByTimeAsync(60000)
    expect(await waiting).toBe('pending')
    const controller = new AbortController(), aborted = store.wait(request.id, 60000, controller.signal)
    controller.abort(); expect(await aborted).toBe('pending')
    expect(vi.getTimerCount()).toBe(0)
    store.settle(request.id, 'accepted')
    expect(await store.wait(request.id, 60000)).toBe('accepted')
  })
})
