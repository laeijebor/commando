import { fetchPanePrs } from '../daemon/paneApi'
import { PANE_PRS } from '../testing/fixtures'
import { PanePrCache } from './prCache'
const host = { id: 'pr-cache', name: 'studio', baseUrl: 'http://studio:4310', auth: { kind: 'token' as const, token: 'secret' } }
jest.mock('../daemon/paneApi', () => ({ fetchPanePrs: jest.fn() }))
beforeEach(() => { jest.useFakeTimers(); jest.clearAllMocks() })
afterEach(() => jest.useRealTimers())
const flush = async () => { for (let i = 0; i < 6; i++) await Promise.resolve() }
it('shares a background request and timer, stops polling invisible rows and bounds stored results', async () => {
  ;(fetchPanePrs as jest.Mock).mockResolvedValue(PANE_PRS)
  const cache = new PanePrCache(2)
  const listener = jest.fn()
  const stop = cache.subscribe(host, '%14', listener)
  const stopOther = cache.subscribe(host, '%14', jest.fn())
  await flush()
  expect(fetchPanePrs).toHaveBeenCalledTimes(1)
  expect(fetchPanePrs).toHaveBeenCalledWith(host, '%14', { background: true })
  expect(listener).toHaveBeenCalledWith({ data: PANE_PRS })
  stop(); stopOther()
  jest.advanceTimersByTime(180_000); await flush()
  expect(fetchPanePrs).toHaveBeenCalledTimes(1)
  const subscriptions = ['%15', '%16'].map((id) => cache.subscribe(host, id, jest.fn()))
  await flush()
  expect(cache.size).toBe(2)
  subscriptions.forEach((unsubscribe) => unsubscribe())
})
it('never overlaps a pending load even across polling ticks', async () => {
  let finish!: (value: typeof PANE_PRS) => void
  ;(fetchPanePrs as jest.Mock).mockReturnValue(new Promise((resolve) => { finish = resolve }))
  const cache = new PanePrCache()
  const stop = cache.subscribe(host, '%14', jest.fn())
  await flush()
  jest.advanceTimersByTime(180_000); await flush()
  expect(fetchPanePrs).toHaveBeenCalledTimes(1)
  finish(PANE_PRS); await flush(); stop()
})

it('publishes a failed first lookup and recovers on the next poll', async () => {
  ;(fetchPanePrs as jest.Mock).mockRejectedValueOnce(new Error('GitHub is disabled')).mockResolvedValue(PANE_PRS)
  const cache = new PanePrCache()
  const listener = jest.fn()
  const stop = cache.subscribe(host, '%14', listener)
  await flush()
  expect(listener).toHaveBeenLastCalledWith({ data: undefined, error: 'GitHub is disabled' })
  const cachedError = jest.fn()
  const stopOther = cache.subscribe(host, '%14', cachedError)
  expect(cachedError).toHaveBeenCalledWith({ data: undefined, error: 'GitHub is disabled' })
  jest.advanceTimersByTime(60_000); await flush()
  expect(listener).toHaveBeenLastCalledWith({ data: PANE_PRS })
  stop(); stopOther()
})
it('keeps stale data alongside refresh errors and clears the error on recovery', async () => {
  ;(fetchPanePrs as jest.Mock).mockResolvedValueOnce(PANE_PRS).mockRejectedValueOnce(new Error('GitHub authentication expired')).mockResolvedValue(PANE_PRS)
  const cache = new PanePrCache()
  const listener = jest.fn()
  const stop = cache.subscribe(host, '%14', listener)
  await flush()
  jest.advanceTimersByTime(60_000); await flush()
  expect(listener).toHaveBeenLastCalledWith({ data: PANE_PRS, error: 'GitHub authentication expired' })
  const stale = jest.fn()
  const stopOther = cache.subscribe(host, '%14', stale)
  expect(stale).toHaveBeenCalledWith({ data: PANE_PRS, error: 'GitHub authentication expired' })
  jest.advanceTimersByTime(60_000); await flush()
  expect(listener).toHaveBeenLastCalledWith({ data: PANE_PRS })
  stop(); stopOther()
})

it('re-reads only the watched lists on one host, in the foreground, when asked', async () => {
  ;(fetchPanePrs as jest.Mock).mockResolvedValue(PANE_PRS)
  const other = { ...host, id: 'other', baseUrl: 'http://other:4310' }
  const cache = new PanePrCache()
  const stops = [cache.subscribe(host, '%14', jest.fn()), cache.subscribe(other, '%14', jest.fn())]
  await flush()
  expect(fetchPanePrs).toHaveBeenCalledTimes(2)
  await cache.refreshHost(host)
  expect(fetchPanePrs).toHaveBeenCalledTimes(3)
  expect(fetchPanePrs).toHaveBeenLastCalledWith(host, '%14', { background: false })
  stops.forEach((stop) => stop())
})

it('keeps the last lists when a forced re-read fails', async () => {
  ;(fetchPanePrs as jest.Mock).mockResolvedValueOnce(PANE_PRS).mockRejectedValueOnce(new Error('GitHub is rate limited'))
  const cache = new PanePrCache()
  const listener = jest.fn()
  const stop = cache.subscribe(host, '%14', listener)
  await flush()
  await cache.refreshHost(host)
  expect(listener).toHaveBeenLastCalledWith({ data: PANE_PRS, error: 'GitHub is rate limited' })
  stop()
})
